"""
Rule-file exporters: keep CLAUDE.md, AGENTS.md, Cursor rules, Copilot
instructions and GEMINI.md in sync with what Mnemosyne knows.

Hooks and MCP deliver context dynamically to tools that support them;
rule files reach every other assistant, and anyone reading the repo.
Mnemosyne owns a clearly marked block inside each file and never touches
the rest, so hand-written instructions live alongside generated ones.

By default only *repository and team* knowledge is exported: these
files are usually committed, and one developer's personal preferences
("keep answers terse") should not be imposed on teammates. Personal
context keeps flowing through hooks and MCP; `audience="personal"`
exports everything, for files the developer keeps to themselves.
"""
from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Literal, Optional

from mnemosyne.context.render import RenderPlan, render_markdown
from mnemosyne.domain.principal import Principal
from mnemosyne.domain.working_context import WorkingContext
from mnemosyne.learning.workspace import detect_repo, detect_working_context

if TYPE_CHECKING:  # pragma: no cover
    from mnemosyne.container import Mnemosyne

Audience = Literal["repo", "personal"]
BEGIN_PREFIX = "<!-- mnemosyne:begin"
BEGIN = "<!-- mnemosyne:begin (generated by `mnemosyne sync`; edits inside this block are overwritten) -->"
END = "<!-- mnemosyne:end -->"
REPO_INTRO = (
    "Conventions and knowledge for this repository, maintained by Mnemosyne from its code, history and the "
    "team's decisions. Follow them unless told otherwise."
)


@dataclass(frozen=True)
class ExportTarget:
    name: str
    path: str
    #: "block": a managed block inside a shared file; "file": Mnemosyne owns the file.
    mode: Literal["block", "file"]
    preamble: str = ""


TARGETS: dict[str, ExportTarget] = {
    "claude": ExportTarget("claude", "CLAUDE.md", "block"),
    "agents": ExportTarget("agents", "AGENTS.md", "block"),
    "copilot": ExportTarget("copilot", ".github/copilot-instructions.md", "block"),
    "gemini": ExportTarget("gemini", "GEMINI.md", "block"),
    "cursor": ExportTarget(
        "cursor",
        ".cursor/rules/mnemosyne.mdc",
        "file",
        preamble="---\ndescription: Repository conventions maintained by Mnemosyne\nalwaysApply: true\n---\n\n",
    ),
}


@dataclass(frozen=True)
class ExportResult:
    target: str
    path: Path
    action: Literal["created", "updated", "unchanged"]
    items: int


def upsert_block(existing: str, block: str) -> str:
    """Replace the managed block if present, otherwise append it."""
    start = existing.find(BEGIN_PREFIX)
    end = existing.find(END, start) if start != -1 else -1
    if start != -1 and end != -1:
        return existing[:start] + block + existing[end + len(END):]
    if not existing.strip():
        return block + "\n"
    return existing.rstrip() + "\n\n" + block + "\n"


def remove_block(existing: str) -> str:
    start = existing.find(BEGIN_PREFIX)
    end = existing.find(END, start) if start != -1 else -1
    if start == -1 or end == -1:
        return existing
    remainder = existing[:start].rstrip() + "\n\n" + existing[end + len(END):].lstrip("\n")
    return remainder.strip() + "\n" if remainder.strip() else ""


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)


def build_profile_markdown(
    container: Mnemosyne,
    context: WorkingContext,
    *,
    audience: Audience = "repo",
    principal: Optional[Principal] = None,
    max_tokens: int = 3000,
) -> tuple[str, int]:
    """The rule-file body for a working context, and how many memories it
    holds. Also served by `GET /api/v1/rules` for team deployments."""
    pack = container.context.profile(context, principal=principal, max_tokens=max_tokens)
    items = pack.items
    if audience == "repo":
        items = [i for i in items if i.memory.scope.startswith("repo:") or i.memory.team_id is not None]
    for item in items:
        item.detail = True  # rule files are read by people too: include the why
    plan = RenderPlan(context=pack.context, task=None, items=items)
    title = "Repository conventions (Mnemosyne)" if audience == "repo" else "Developer memory (Mnemosyne)"
    body = render_markdown(plan, wrap=False, title=title, intro=REPO_INTRO if audience == "repo" else None)
    return body, len(items)


def repository_root(repo_path: str | Path) -> Path:
    repo = detect_repo(Path(repo_path))
    return (repo.root if repo else Path(repo_path)).resolve()


def write_rule_files(
    root: Path,
    body: str,
    items: int,
    *,
    targets: list[str],
    dry_run: bool = False,
) -> list[ExportResult]:
    """Write `body` into each target's file under `root`: a managed block
    inside shared files, the whole file for files Mnemosyne owns."""
    unknown = [t for t in targets if t not in TARGETS]
    if unknown:
        raise ValueError(f"unknown export targets {unknown}; choose from {sorted(TARGETS)}")
    block = f"{BEGIN}\n{body.rstrip()}\n{END}"
    results = []
    for name in targets:
        target = TARGETS[name]
        path = (root / target.path).resolve()
        if root not in path.parents:
            raise ValueError(f"refusing to write outside the repository: {path}")
        existing = path.read_text(encoding="utf-8") if path.exists() else ""
        new = target.preamble + body if target.mode == "file" else upsert_block(existing, block)
        if new == existing:
            action: Literal["created", "updated", "unchanged"] = "unchanged"
        else:
            action = "updated" if existing else "created"
            if not dry_run:
                _atomic_write(path, new)
        results.append(ExportResult(name, path, action, items))
    return results


def export(
    container: Mnemosyne,
    repo_path: str | Path,
    *,
    targets: list[str],
    audience: Audience = "repo",
    principal: Optional[Principal] = None,
    dry_run: bool = False,
) -> list[ExportResult]:
    root = repository_root(repo_path)
    body, count = build_profile_markdown(container, detect_working_context(root), audience=audience,
                                         principal=principal)
    return write_rule_files(root, body, count, targets=targets, dry_run=dry_run)
