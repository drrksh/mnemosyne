"""
Repository file inventory.

Prefers `git ls-files` (exactly the tracked files, so .gitignore is
honoured for free) and falls back to a directory walk with a standard
ignore list. Vendored, generated and minified files are excluded: an
autogenerated migration or a bundled dependency says nothing about how
the developer writes code.
"""
from __future__ import annotations

import os
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

from mnemosyne.learning.workspace import EXTENSION_LANGUAGES, run_git

IGNORED_DIRS = frozenset(
    {
        ".git", "node_modules", "vendor", "third_party", "third-party", "dist", "build", "out", "target",
        ".venv", "venv", "env", "__pycache__", ".mypy_cache", ".pytest_cache", ".ruff_cache", ".tox", ".nox",
        ".next", ".nuxt", ".svelte-kit", "coverage", "htmlcov", ".idea", ".vscode", "bower_components",
        ".gradle", ".terraform", "Pods", "DerivedData", "site-packages",
    }
)
GENERATED_MARKERS = (
    "/migrations/versions/",
    "/alembic/versions/",
    "_pb2.py",
    "_pb2_grpc.py",
    ".pb.go",
    ".min.js",
    ".bundle.js",
    ".generated.",
    "/generated/",
    "/__generated__/",
    ".d.ts",
)


@dataclass
class FileInventory:
    root: Path
    #: language -> relative paths (all eligible files, sorted)
    by_language: dict[str, list[str]] = field(default_factory=dict)
    all_files: list[str] = field(default_factory=list)
    used_git: bool = False

    def sample(self, language: str, limit: int) -> list[str]:
        """Deterministic, evenly spread sample (not just the first N, which
        would over-represent one directory)."""
        paths = self.by_language.get(language, [])
        if len(paths) <= limit:
            return list(paths)
        step = len(paths) / limit
        return [paths[int(i * step)] for i in range(limit)]

    def has(self, relative: str) -> bool:
        return (self.root / relative).exists()


def _is_generated(path: str) -> bool:
    normalized = "/" + path.replace(os.sep, "/")
    return any(marker in normalized for marker in GENERATED_MARKERS)


def _walk(root: Path, max_files: int) -> list[str]:
    found: list[str] = []
    for current, dirs, files in os.walk(root):
        dirs[:] = sorted(d for d in dirs if d not in IGNORED_DIRS and not d.startswith("."))
        for name in sorted(files):
            found.append(os.path.relpath(os.path.join(current, name), root))
            if len(found) >= max_files * 4:
                return found
    return found


def build_inventory(root: Path, *, max_files: int = 4000, max_file_bytes: int = 400_000) -> FileInventory:
    inventory = FileInventory(root=root)
    listing = run_git(root, "ls-files", "-z", "--cached", "--others", "--exclude-standard")
    if listing is not None:
        candidates = [p for p in listing.split("\0") if p]
        inventory.used_git = True
    else:
        candidates = _walk(root, max_files)

    by_language: dict[str, list[str]] = defaultdict(list)
    kept: list[str] = []
    for relative in sorted(candidates):
        parts = Path(relative).parts
        if any(part in IGNORED_DIRS for part in parts[:-1]) or _is_generated(relative):
            continue
        kept.append(relative)
        language = EXTENSION_LANGUAGES.get(Path(relative).suffix.lower())
        if language is None:
            continue
        try:
            size = (root / relative).stat().st_size
        except OSError:
            continue
        if 0 < size <= max_file_bytes:
            by_language[language].append(relative)
        if len(kept) >= max_files:
            break
    inventory.all_files = kept
    inventory.by_language = dict(by_language)
    return inventory


def read_text(root: Path, relative: str) -> str:
    try:
        return (root / relative).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def count_lines(root: Path, paths: list[str]) -> int:
    total = 0
    for relative in paths:
        try:
            with (root / relative).open("rb") as handle:
                total += sum(1 for _ in handle)
        except OSError:
            continue
    return total
